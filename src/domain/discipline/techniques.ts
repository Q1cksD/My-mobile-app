const techniquesById = new Map(DISCIPLINE_TECHNIQUES.map((item) => [item.id, item]));

export interface ActiveTechniqueGuide {
  id: string;
  title: string;
  hintText: string;
}

export function getDisciplineTechniqueById(id: string): DisciplineTechnique | null {
  return techniquesById.get(id) ?? null;
}

export function getTechniqueOfDay(activeIds: string[], dayInChapter: number): DisciplineTechnique | null {
  if (!activeIds.length) {
    return null;
  }
  const index = Math.abs(dayInChapter) % activeIds.length;
  const id = activeIds[index] ?? activeIds[0];
  if (!id) {
    return null;
  }
  return getDisciplineTechniqueById(id);
}

export function getActiveTechniqueGuides(
  activeIds: string[],
  techniquesMap: ReadonlyMap<string, DisciplineTechnique> = techniquesById,
): ActiveTechniqueGuide[] {
  return activeIds
    .map((id) => {
      const technique = techniquesMap.get(id);
      if (!technique) {
        return null;
      }

      return {
        id: technique.id,
        title: technique.titleRu,
        hintText: technique.tipsRu[0] ?? technique.howToRu[0] ?? technique.shortRu,
      };
    })
    .filter((item): item is ActiveTechniqueGuide => item !== null);
}

export function getActiveTechniqueHints(activeIds: string[], dayInChapter: number): string {
  const technique = getTechniqueOfDay(activeIds, dayInChapter);
  if (!technique || !technique.howToRu.length) {
    return 'Сформируйте активные техники, чтобы получать подсказку дня.';
  }

  const stepIndex = Math.abs(dayInChapter) % technique.howToRu.length;
  const step = technique.howToRu[stepIndex] ?? technique.howToRu[0];
  return `Подсказка дня: ${step}`;
}
